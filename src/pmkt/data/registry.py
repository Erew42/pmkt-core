_NAME_TO_VERSION = {spec.name: version for version, spec in SCHEMA_REGISTRY.items()}

SCHEMA_DOCUMENTATION_ALLOWLIST: dict[str, str] = {}


def list_table_specs() -> tuple[TableSpec, ...]:
    return tuple(SCHEMA_REGISTRY[version] for version in sorted(SCHEMA_REGISTRY))


def schema_documentation_gaps(documented_versions: Iterable[str]) -> dict[str, str]:
    documented = set(documented_versions)
    return {
        version: "missing from docs/data_dictionary.md"
        for version in sorted(SCHEMA_REGISTRY)
        if version not in documented and version not in SCHEMA_DOCUMENTATION_ALLOWLIST
    }


def get_table_spec(name_or_version: str) -> TableSpec:
    key = name_or_version.strip()
    version = key if key in SCHEMA_REGISTRY else _NAME_TO_VERSION.get(key)
    if version is None:
        known = ", ".join(sorted(SCHEMA_REGISTRY))
        raise KeyError(f"unknown schema {name_or_version!r}; known schemas: {known}")
    return SCHEMA_REGISTRY[version]


def infer_table_spec(columns: Iterable[str], schema_version: str | None = None) -> TableSpec:
    if schema_version:
        return get_table_spec(schema_version)
    column_set = set(columns)
    matches = [spec for spec in SCHEMA_REGISTRY.values() if set(spec.columns).issubset(column_set)]
    if len(matches) == 1:
        return matches[0]
    if matches:
        versions = ", ".join(sorted(spec.version for spec in matches))
        raise KeyError(f"ambiguous schema inference among: {versions}; pass an explicit schema id")
    raise KeyError("could not infer schema; pass an explicit schema id")


def arrow_schema(spec: TableSpec) -> pa.Schema:
    import pyarrow as pa

    arrow_types = {
        "bool": pa.bool_(),
        "float64": pa.float64(),
        "int64": pa.int64(),
        "int32": pa.int32(),
        "json": pa.string(),
        "large_string": pa.large_string(),
        "list[string]": pa.list_(pa.string()),
        "string": pa.string(),
    }
    return pa.schema(
        [
            pa.field(field.name, arrow_types.get(field.dtype, pa.string()), nullable=field.nullable)
            for field in spec.fields
        ]
    )


