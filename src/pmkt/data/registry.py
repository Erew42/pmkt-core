def _dtype_for(column: str) -> str:
    try:
        return _EXPLICIT_COLUMN_DTYPES[column]
    except KeyError:
        raise KeyError(
            f"schema column {column!r} has no explicit dtype; add it to "
            "_EXPLICIT_COLUMN_DTYPES"
        ) from None


def _field(
    column: str,
    *,
    nullable: bool = True,
    dtype: str | None = None,
    unit: str | None = None,
    allowed_values: tuple[str, ...] | None = None,
) -> FieldSpec:
    if column == "schema_version":
        nullable = False
    if column in {"venue", "exchange", "platform"} or column.endswith("_exchange"):
        allowed_values = _VENUES
    if column == "outcome":
        allowed_values = _OUTCOMES
    if column == "side":
        allowed_values = _DEPTH_SIDES
    if column in {"status"} and unit is None:
        unit = None
    if column == "status" and dtype is None:
        dtype = "string"
    if column == "schema_version":
        dtype = "string"
    if column.endswith("_dollars"):
        unit = "USD probability dollars"
    elif column.endswith("_contracts"):
        unit = "contracts"
    elif column.endswith("_bps"):
        unit = "basis points"
    elif column.endswith("_ms"):
        unit = "milliseconds"
    elif column.endswith("_utc"):
        unit = "UTC"
    return FieldSpec(
        name=column,
        dtype=dtype or _dtype_for(column),
        nullable=nullable,
        unit=unit,
        allowed_values=allowed_values,
    )


def _fields(
    columns: Iterable[str],
    *,
    required: set[str] | None = None,
) -> tuple[FieldSpec, ...]:
    required = required or set()
    return tuple(_field(column, nullable=column not in required) for column in columns)


def _table(
    name: str,
    version: str,
    columns: Iterable[str],
    *,
    primary_key: tuple[str, ...] = (),
    required: set[str] | None = None,
    description: str = "",
) -> TableSpec:
    required_set = {"schema_version", *primary_key}
    if required:
        required_set.update(required)
    fields = _fields(columns, required=required_set)
    if version == RUN_MANIFEST_SCHEMA_VERSION:
        fields = tuple(
            replace(field, allowed_values=_MANIFEST_STATUSES)
            if field.name == "status"
            else field
            for field in fields
        )
    if version == SOAK_RUN_REPORT_SCHEMA_VERSION:
        fields = tuple(
            replace(field, allowed_values=_SOAK_REPORT_STATUSES)
            if field.name == "status"
            else replace(field, allowed_values=_SOAK_REPORT_DECISIONS)
            if field.name == "decision"
            else field
            for field in fields
        )
    if version == PASSIVE_QUOTE_EVALUATION_SCHEMA_VERSION:
        fields = tuple(
            replace(field, allowed_values=None)
            if field.name in {"venue", "side"}
            else field
            for field in fields
        )
    return TableSpec(
        name=name,
        version=version,
        fields=fields,
        primary_key=primary_key,
        description=description,
    )


def _typed_table(
    name: str,
    version: str,
    fields: Iterable[
        tuple[str, str, bool] | tuple[str, str, bool, tuple[str, ...] | None]
    ],
    *,
    primary_key: tuple[str, ...] = (),
    description: str = "",
) -> TableSpec:
    """Build a table whose field dtypes are local to the schema.

    Most legacy schemas share the repository's global column-name dtype map.
    Tape contracts deliberately type some familiar names differently (for
    example venue sequence is lossless text), so they must not mutate that map.
    """
    typed_fields: list[FieldSpec] = []
    for item in fields:
        column, dtype, nullable, *rest = item
        allowed_values = rest[0] if rest else None
        typed_fields.append(
            FieldSpec(
                name=column,
                dtype=dtype,
                nullable=nullable,
                allowed_values=allowed_values,
            )
        )
    return TableSpec(
        name=name,
        version=version,
        fields=tuple(typed_fields),
        primary_key=primary_key,
        description=description,
    )


